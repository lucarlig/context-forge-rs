CREATE TABLE IF NOT EXISTS global_config (
    id INTEGER PRIMARY KEY NOT NULL,
    passthrough_headers JSON
);

CREATE TABLE IF NOT EXISTS gateways (
    id VARCHAR(36) PRIMARY KEY NOT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    url VARCHAR(767) NOT NULL,
    description TEXT,
    transport VARCHAR(20) NOT NULL,
    capabilities JSON NOT NULL DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_seen TIMESTAMP WITH TIME ZONE,
    auth_type VARCHAR(20),
    auth_value JSON,
    reachable BOOLEAN NOT NULL DEFAULT TRUE,
    passthrough_headers JSON,
    tags JSON NOT NULL DEFAULT '[]',
    created_by VARCHAR(255),
    created_from_ip VARCHAR(45),
    created_via VARCHAR(100),
    created_user_agent TEXT,
    modified_by VARCHAR(255),
    modified_from_ip VARCHAR(45),
    modified_via VARCHAR(100),
    modified_user_agent TEXT,
    import_batch_id VARCHAR(36),
    federation_source VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 1,
    oauth_config JSON,
    team_id VARCHAR(36) REFERENCES email_teams(id) ON DELETE SET NULL,
    owner_email VARCHAR(255),
    visibility VARCHAR(20) NOT NULL DEFAULT 'private',
    ca_certificate TEXT,
    ca_certificate_sig VARCHAR(64),
    signing_algorithm VARCHAR(20),
    refresh_interval_seconds INTEGER,
    last_refresh_at TIMESTAMP WITH TIME ZONE,
    auth_query_params JSON,
    gateway_mode VARCHAR(20) NOT NULL DEFAULT 'cache',
    client_cert TEXT,
    client_key TEXT,
    identity_propagation JSON,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    status_message TEXT,
    registration_attempts INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP WITH TIME ZONE,
    last_error TEXT,
    lifecycle_claimed_by VARCHAR(64),
    lifecycle_claimed_at TIMESTAMP WITH TIME ZONE,
    lifecycle_claim_expires_at TIMESTAMP WITH TIME ZONE,
    add_headers JSON,
    remove_headers JSON,
    upstream_instructions TEXT,
    tool_validation_policy TEXT,
    sigv4_config JSON
);

CREATE INDEX IF NOT EXISTS idx_gateways_catalog_slug ON gateways (slug, visibility, team_id);
CREATE INDEX IF NOT EXISTS idx_gateways_catalog_url ON gateways (url, visibility, team_id, owner_email);

CREATE TABLE IF NOT EXISTS tools (
    id VARCHAR(36) PRIMARY KEY NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    custom_name_slug VARCHAR(255) NOT NULL,
    url VARCHAR(767),
    description TEXT,
    integration_type VARCHAR(20) NOT NULL DEFAULT 'MCP',
    request_type VARCHAR(20) NOT NULL DEFAULT 'SSE',
    headers JSON,
    input_schema JSON NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    jsonpath_filter TEXT NOT NULL DEFAULT '',
    auth_type VARCHAR(20),
    auth_value TEXT,
    gateway_id VARCHAR(36) REFERENCES gateways(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    annotations JSON,
    reachable BOOLEAN NOT NULL DEFAULT TRUE,
    tags JSON NOT NULL DEFAULT '[]',
    created_by VARCHAR(255),
    created_from_ip VARCHAR(45),
    created_via VARCHAR(100),
    created_user_agent TEXT,
    modified_by VARCHAR(255),
    modified_from_ip VARCHAR(45),
    modified_via VARCHAR(100),
    modified_user_agent TEXT,
    import_batch_id VARCHAR(36),
    federation_source VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 1,
    custom_name VARCHAR(255) NOT NULL,
    display_name VARCHAR(255),
    team_id VARCHAR(36) REFERENCES email_teams(id) ON DELETE SET NULL,
    owner_email VARCHAR(255),
    visibility VARCHAR(20) NOT NULL DEFAULT 'private',
    output_schema JSON,
    base_url VARCHAR,
    path_template VARCHAR,
    query_mapping JSON,
    header_mapping JSON,
    timeout_ms INTEGER,
    expose_passthrough BOOLEAN NOT NULL DEFAULT TRUE,
    allowlist JSON,
    plugin_chain_pre JSON,
    plugin_chain_post JSON,
    original_description TEXT,
    title VARCHAR(255),
    grpc_service_id VARCHAR(36),
    deprecated BOOLEAN NOT NULL DEFAULT FALSE,
    extension_metadata JSON,
    tool_validation_policy TEXT,
    validation_refusal TEXT,
    sigv4_config JSON,
    UNIQUE (gateway_id, original_name)
);

CREATE INDEX IF NOT EXISTS idx_tools_catalog_enabled_name ON tools (name, id) WHERE enabled = TRUE;

CREATE TABLE IF NOT EXISTS resources (
    id VARCHAR(36) PRIMARY KEY NOT NULL,
    uri VARCHAR(767) NOT NULL,
    uri_template TEXT,
    name VARCHAR(255) NOT NULL,
    original_name TEXT,
    custom_name_slug TEXT,
    title VARCHAR(255),
    description TEXT,
    mime_type VARCHAR(255),
    size INTEGER,
    text_content TEXT,
    binary_content BYTEA,
    extension_metadata JSON,
    enabled BOOLEAN DEFAULT TRUE,
    tags JSON NOT NULL DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    created_from_ip VARCHAR(45),
    created_via VARCHAR(100),
    created_user_agent TEXT,
    modified_by VARCHAR(255),
    modified_from_ip VARCHAR(45),
    modified_via VARCHAR(100),
    modified_user_agent TEXT,
    import_batch_id VARCHAR(36),
    federation_source VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 1,
    gateway_id VARCHAR(36) REFERENCES gateways(id) ON DELETE CASCADE,
    team_id VARCHAR(36) REFERENCES email_teams(id) ON DELETE SET NULL,
    owner_email VARCHAR(255),
    visibility VARCHAR(20) NOT NULL DEFAULT 'public'
);

CREATE TABLE IF NOT EXISTS prompts (
    id VARCHAR(36) PRIMARY KEY NOT NULL,
    name VARCHAR(255) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    custom_name VARCHAR(255) NOT NULL,
    custom_name_slug VARCHAR(255) NOT NULL,
    title VARCHAR(255),
    description TEXT,
    template TEXT,
    argument_schema JSON,
    enabled BOOLEAN DEFAULT TRUE,
    tags JSON NOT NULL DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    gateway_id VARCHAR(36) REFERENCES gateways(id) ON DELETE CASCADE,
    team_id VARCHAR(36) REFERENCES email_teams(id) ON DELETE SET NULL,
    owner_email VARCHAR(255),
    visibility VARCHAR(20) NOT NULL DEFAULT 'public',
    UNIQUE (gateway_id, original_name)
);

CREATE TABLE IF NOT EXISTS servers (
    id VARCHAR(36) PRIMARY KEY NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    icon VARCHAR,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    tags JSON NOT NULL DEFAULT '[]',
    created_by VARCHAR(255),
    created_from_ip VARCHAR(45),
    created_via VARCHAR(100),
    created_user_agent TEXT,
    modified_by VARCHAR(255),
    modified_from_ip VARCHAR(45),
    modified_via VARCHAR(100),
    modified_user_agent TEXT,
    import_batch_id VARCHAR(36),
    federation_source VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 1,
    team_id VARCHAR(36) REFERENCES email_teams(id) ON DELETE SET NULL,
    owner_email VARCHAR(255),
    visibility VARCHAR(20) NOT NULL DEFAULT 'private',
    oauth_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    oauth_config JSON,
    instructions TEXT,
    oauth_config_approved BOOLEAN NOT NULL DEFAULT FALSE,
    oauth_config_generation VARCHAR(32)
);

CREATE TABLE IF NOT EXISTS server_tool_association (
    server_id VARCHAR(36) NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    tool_id VARCHAR(36) NOT NULL REFERENCES tools(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, tool_id)
);

CREATE INDEX IF NOT EXISTS idx_server_tool_association_tool_id ON server_tool_association (tool_id);

CREATE TABLE IF NOT EXISTS server_resource_association (
    server_id VARCHAR(36) NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    resource_id VARCHAR(36) NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, resource_id)
);

CREATE TABLE IF NOT EXISTS server_prompt_association (
    server_id VARCHAR(36) NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    prompt_id VARCHAR(36) NOT NULL REFERENCES prompts(id) ON DELETE CASCADE,
    PRIMARY KEY (server_id, prompt_id)
);
