CREATE TABLE IF NOT EXISTS grpc_services (
    id VARCHAR(36) PRIMARY KEY NOT NULL,
    name VARCHAR(255) NOT NULL UNIQUE,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    target VARCHAR(767) NOT NULL,
    reflection_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    tls_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    tls_cert_path VARCHAR(767),
    tls_key_path VARCHAR(767),
    grpc_metadata JSON NOT NULL DEFAULT '{}',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    reachable BOOLEAN NOT NULL DEFAULT FALSE,
    service_count INTEGER NOT NULL DEFAULT 0,
    method_count INTEGER NOT NULL DEFAULT 0,
    discovered_services JSON NOT NULL DEFAULT '{}',
    last_reflection TIMESTAMP WITH TIME ZONE,
    tags JSON NOT NULL DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    created_from_ip VARCHAR(45),
    created_via VARCHAR(100),
    created_user_agent TEXT,
    modified_by VARCHAR(255),
    modified_from_ip VARCHAR(45),
    modified_via VARCHAR(100),
    modified_user_agent TEXT,
    import_batch_id VARCHAR(36),
    federation_source VARCHAR(255),
    version INTEGER NOT NULL DEFAULT 1,
    team_id VARCHAR(36) REFERENCES email_teams(id) ON DELETE SET NULL,
    owner_email VARCHAR(255),
    visibility VARCHAR(20) NOT NULL DEFAULT 'public'
);

CREATE INDEX IF NOT EXISTS idx_tools_grpc_service ON tools (grpc_service_id);
