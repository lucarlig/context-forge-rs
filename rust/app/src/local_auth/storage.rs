macro_rules! account_tables {
    ($identity:literal) => {
        concat!(
            "CREATE TABLE IF NOT EXISTS email_auth_events (
                id ", $identity, ",
                timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
                user_email VARCHAR(255),
                event_type VARCHAR(50) NOT NULL,
                success BOOLEAN NOT NULL,
                ip_address VARCHAR(45),
                user_agent TEXT,
                failure_reason VARCHAR(255),
                details TEXT
            );
            CREATE INDEX IF NOT EXISTS ix_email_auth_events_user_email ON email_auth_events(user_email);
            CREATE TABLE IF NOT EXISTS cf_local_sessions (
                jti VARCHAR(36) PRIMARY KEY NOT NULL,
                user_email VARCHAR(255) NOT NULL REFERENCES email_users(email) ON DELETE CASCADE,
                issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
                expires_at TIMESTAMP WITH TIME ZONE NOT NULL
            );
            CREATE INDEX IF NOT EXISTS cf_local_sessions_owner_expiry ON cf_local_sessions(user_email,expires_at);
            CREATE TABLE IF NOT EXISTS password_history(
                id VARCHAR(36) PRIMARY KEY NOT NULL,
                user_email VARCHAR(255) NOT NULL REFERENCES email_users(email) ON DELETE CASCADE,
                password_hash TEXT NOT NULL,
                changed_at TIMESTAMP WITH TIME ZONE NOT NULL
            );
            CREATE INDEX IF NOT EXISTS ix_password_history_user_email_changed_at ON password_history(user_email,changed_at);
            CREATE TABLE IF NOT EXISTS password_reset_tokens(
                id VARCHAR(36) PRIMARY KEY NOT NULL,
                user_email VARCHAR(255) NOT NULL REFERENCES email_users(email) ON DELETE CASCADE,
                token_hash VARCHAR(64) NOT NULL UNIQUE,
                expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                used_at TIMESTAMP WITH TIME ZONE,
                created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                ip_address VARCHAR(45),
                user_agent TEXT
            );
            CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_user_email ON password_reset_tokens(user_email);
            CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_expires_at ON password_reset_tokens(expires_at);"
        )
    };
}

pub(crate) const SQLITE_MIGRATION: &str = account_tables!("INTEGER PRIMARY KEY");
pub(crate) const POSTGRES_MIGRATION: &str =
    account_tables!("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");

