#[derive(sqlx::FromRow)]
pub(super) struct LocalUser {
    pub(super) id: String,
    pub(super) email: String,
    pub(super) password_hash: Option<String>,
    pub(super) full_name: Option<String>,
    pub(super) is_admin: bool,
    pub(super) is_active: bool,
    pub(super) auth_provider: String,
    pub(super) created_at: String,
    pub(super) last_login: Option<String>,
    pub(super) email_verified: bool,
    pub(super) failed_login_attempts: i32,
    pub(super) locked_until: Option<String>,
    pub(super) password_change_required: bool,
    pub(super) password_changed_at: Option<String>,
}

impl LocalUser {
    pub(super) fn locked(&self, now: Timestamp) -> bool {
        self.locked_until
            .as_deref()
            .and_then(parse_timestamp)
            .is_some_and(|locked| locked > now)
    }

    pub(super) fn metadata(&self) -> Value {
        let time = |value: Option<&str>| value.map(|value| value.replacen(' ', "T", 1));
        json!({
            "email":self.email,
            "full_name":self.full_name,
            "is_admin":self.is_admin,
            "is_active":self.is_active,
            "auth_provider":self.auth_provider,
            "created_at":time(Some(&self.created_at)),
            "last_login":time(self.last_login.as_deref()),
            "email_verified":self.email_verified,
            "failed_login_attempts":self.failed_login_attempts,
            "locked_until":time(self.locked_until.as_deref()),
            "is_locked":self.locked(Timestamp::now()),
            "password_change_required":self.password_change_required,
        })
    }
}

macro_rules! local_user_fields {
    () => {
        "id,email,password_hash,full_name,is_admin,is_active,auth_provider,
    CAST(created_at AS TEXT) AS created_at, CAST(last_login AS TEXT) AS last_login,
    (email_verified_at IS NOT NULL) AS email_verified, failed_login_attempts,
    CAST(locked_until AS TEXT) AS locked_until, password_change_required,
    CAST(password_changed_at AS TEXT) AS password_changed_at"
    };
}

const SELECT_LOCAL_USER: &str = concat!(
    "SELECT ",
    local_user_fields!(),
    " FROM email_users WHERE email=$1"
);

const CREATE_LOCAL_USER: &str = "INSERT INTO email_users
    (id,email,password_hash,full_name,is_admin,is_active,auth_provider,admin_origin,
     password_hash_type,failed_login_attempts,password_change_required,
     email_verified_at,password_changed_at,created_at,updated_at)
    VALUES($1,$2,$3,$4,$5,$6,'local',$7,'argon2id',0,$8,
        CASE WHEN $9 THEN CURRENT_TIMESTAMP ELSE NULL END,
        CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)
    ON CONFLICT(email) DO NOTHING";

const INSERT_PERSONAL_TEAM: &str = "INSERT INTO email_teams
    (id,name,slug,description,created_by,is_personal,visibility,is_active,created_at,updated_at)
    VALUES($1,$2,$3,$4,$5,TRUE,'private',TRUE,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)
    ON CONFLICT(slug) DO NOTHING";

const USE_ROLE: &str = "INSERT INTO user_roles
    (id,user_email,role_id,scope,scope_id,granted_by,granted_at,is_active)
    SELECT $1,$2,id,scope,$3,$4,CURRENT_TIMESTAMP,TRUE FROM roles
    WHERE name=$5 AND scope=$6 AND is_active=TRUE ON CONFLICT DO NOTHING";

