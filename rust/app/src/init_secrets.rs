use std::{
    collections::HashMap,
    env,
    error::Error,
    fmt::Write as _,
    fs::{self, File, Metadata, OpenOptions},
    io::{self, Read, Write},
    path::{Path, PathBuf},
};

use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use clap::Parser;
use ring::rand::{SecureRandom, SystemRandom};
use zeroize::Zeroizing;

use crate::private_file;

mod env_file;

type CliError = Box<dyn Error + Send + Sync>;
const KEY_BYTES: usize = 32;
const PASSWORD_BYTES: usize = 18;
const ENCRYPTION_SECRET: &str = "AUTH_ENCRYPTION_SECRET";
const FIELDS: [(&str, usize); 5] = [
    ("JWT_SECRET_KEY", KEY_BYTES),
    (ENCRYPTION_SECRET, KEY_BYTES),
    ("BASIC_AUTH_PASSWORD", PASSWORD_BYTES),
    ("PLATFORM_ADMIN_PASSWORD", PASSWORD_BYTES),
    ("DEFAULT_USER_PASSWORD", PASSWORD_BYTES),
];

#[derive(Parser)]
#[command(
    name = "context-forge-rs init-secrets",
    about = "Generate secrets for gateway deployment"
)]
struct Options {
    /// Write a new secrets file at this path.
    #[arg(long, default_value = ".env.secrets")]
    output: PathBuf,
    /// Overwrite the output file without a prompt.
    #[arg(long)]
    force: bool,
    /// Print generated values to stdout.
    #[arg(long)]
    stdout: bool,
    /// Replace weak deployment secrets in this environment file.
    #[arg(long, value_name = "ENV_FILE")]
    patch_env: Option<PathBuf>,
}

pub fn run() -> Result<(), CliError> {
    let options = Options::parse_from(env::args_os().skip(1));
    if let Some(path) = options.patch_env {
        return patch(&path);
    }
    if options.stdout {
        return Ok(io::stdout().lock().write_all(generated()?.as_bytes())?);
    }
    let path = options.output;
    let existing = regular_metadata(&path)?;
    if existing.is_some() && !options.force && !confirm(&path)? {
        println!("Existing file kept unchanged.");
        return Ok(());
    }
    let mut contents = Zeroizing::new("# Generated by context-forge-rs init-secrets\n".to_owned());
    contents.push_str(&generated()?);
    if let Some(ref snapshot) = existing {
        require_current(&path, snapshot)?;
    }
    private_file::write(&path, contents.as_bytes(), existing.is_some())?;
    println!("Secrets written to {}", path.display());
    Ok(())
}

fn confirm(path: &Path) -> io::Result<bool> {
    print!("{} already exists. Overwrite? [y/N] ", path.display());
    io::stdout().flush()?;
    let mut answer = String::new();
    io::stdin().read_line(&mut answer)?;
    Ok(matches!(
        answer.trim().to_ascii_lowercase().as_str(),
        "y" | "yes"
    ))
}

fn generated() -> Result<Zeroizing<String>, CliError> {
    let mut contents = Zeroizing::new(String::new());
    for (name, bytes) in FIELDS {
        writeln!(contents, "{name}={}", token(bytes)?.as_str())?;
    }
    Ok(contents)
}

fn token(bytes: usize) -> Result<Zeroizing<String>, CliError> {
    let mut random = Zeroizing::new(Vec::new());
    random.try_reserve_exact(bytes)?;
    random.resize(bytes, 0);
    SystemRandom::new()
        .fill(&mut random)
        .map_err(|_| "could not generate random data")?;
    Ok(Zeroizing::new(URL_SAFE_NO_PAD.encode(&*random)))
}

fn patch(path: &Path) -> Result<(), CliError> {
    if env::var("MCPGATEWAY_AUTO_INIT_SECRETS")
        .is_ok_and(|value| value.eq_ignore_ascii_case("false"))
    {
        println!("Secret generation is disabled.");
        return Ok(());
    }
    let mut existing = open_env_file(path)?;
    let mut original = Zeroizing::new(String::new());
    let snapshot = if let Some(file) = &mut existing {
        file.lock()?;
        let snapshot = file.metadata()?;
        require_current(path, &snapshot)?;
        file.read_to_string(&mut original)?;
        Some(snapshot)
    } else {
        None
    };
    let document = env_file::EnvFile::parse(&original)?;
    let configured_minimum = secret_minimum(document.get("MIN_SECRET_LENGTH"))?;
    let mut changes = Vec::new();
    for (name, bytes) in FIELDS {
        let environment = environment(name)?;
        let stored = document.get(name);
        let current = environment
            .as_deref()
            .map(String::as_str)
            .or(stored)
            .unwrap_or_default();
        let key = bytes == KEY_BYTES;
        if !weak(current, key, configured_minimum) {
            continue;
        }
        if environment.is_some() {
            if name == ENCRYPTION_SECRET && stored.is_some_and(|value| !value.trim().is_empty()) {
                return Err("AUTH_ENCRYPTION_SECRET in the environment would replace the existing file value. Use the existing key or run a migration-aware rotation.".into());
            }
            if !key && stored.is_none() {
                continue;
            }
        }
        let size = if key { configured_minimum } else { bytes };
        changes.push((name, token(size)?));
    }
    if changes.is_empty() {
        println!("{}: no changes made", path.display());
        return Ok(());
    }
    let updated = document.update(&changes);
    if let Some(ref snapshot) = snapshot {
        require_current(path, snapshot)?;
    }
    private_file::write(path, updated.as_bytes(), snapshot.is_some())?;
    let names = changes.iter().map(|(name, _)| *name).collect::<Vec<_>>();
    println!("Patched {}: {}", path.display(), names.join(", "));
    Ok(())
}

fn secret_minimum(file: Option<&str>) -> Result<usize, CliError> {
    let environment = environment("MIN_SECRET_LENGTH")?;
    let minimum = environment
        .as_deref()
        .map(String::as_str)
        .or(file.filter(|value| !value.is_empty()))
        .unwrap_or("32")
        .trim()
        .parse::<usize>()
        .map_err(|_| "MIN_SECRET_LENGTH must be a whole number")?;
    if minimum < KEY_BYTES {
        return Err("MIN_SECRET_LENGTH must be at least 32".into());
    }
    Ok(minimum)
}

fn weak(value: &str, key: bool, minimum: usize) -> bool {
    let lower = Zeroizing::new(value.to_ascii_lowercase());
    value.trim().is_empty()
        || lower.starts_with("__replace_me__")
        || lower.starts_with("replaceme")
        || matches!(
            lower.as_str(),
            "my-test-key"
                | "my-test-key-but-now-longer-than-32-bytes"
                | "my-test-salt"
                | "changeme"
                | "secret"
                | "password"
                | "test-secret"
                | "my-secret"
                | "12345678"
        )
        || (key && (value.chars().count() < minimum || entropy(value) < 3.5))
}

fn entropy(value: &str) -> f64 {
    let mut counts = HashMap::new();
    let mut length = 0;
    for ch in value.chars() {
        *counts.entry(ch).or_insert(0) += 1;
        length += 1;
    }
    -counts
        .into_values()
        .map(|count| {
            let proportion = f64::from(count) / f64::from(length);
            proportion * proportion.log2()
        })
        .sum::<f64>()
}

fn environment(name: &str) -> Result<Option<Zeroizing<String>>, CliError> {
    match env::var(name) {
        Ok(value) => Ok(Some(Zeroizing::new(value))),
        Err(env::VarError::NotPresent) => Ok(None),
        Err(env::VarError::NotUnicode(_)) => Err(format!("invalid Unicode in {name}").into()),
    }
}

fn regular_metadata(path: &Path) -> io::Result<Option<Metadata>> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.is_file() => Ok(Some(metadata)),
        Ok(_) => Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "the secret file path must refer to a regular file",
        )),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error),
    }
}

fn open_env_file(path: &Path) -> io::Result<Option<File>> {
    if regular_metadata(path)?.is_none() {
        return Ok(None);
    }
    let mut options = OpenOptions::new();
    options.read(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;

        options.custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
    }
    let file = options.open(path)?;
    if !file.metadata()?.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "the environment file must be regular",
        ));
    }
    Ok(Some(file))
}

fn require_current(path: &Path, snapshot: &Metadata) -> io::Result<()> {
    if let Some(current) = regular_metadata(path)? {
        #[cfg(unix)]
        {
            use std::os::unix::fs::MetadataExt;

            if (current.dev(), current.ino()) != (snapshot.dev(), snapshot.ino()) {
                return Err(io::Error::other(
                    "the secret file changed during the update",
                ));
            }
        }
        if current.len() == snapshot.len() && current.modified()? == snapshot.modified()? {
            return Ok(());
        }
    }
    Err(io::Error::other(
        "the secret file changed during the update",
    ))
}
