impl Database {
    pub(crate) async fn active_token_owner(
        &self,
        email: &str,
    ) -> Result<Option<(String, String, bool)>, sqlx::Error> {
        const QUERY: &str = "SELECT id,email,is_admin FROM email_users WHERE LOWER(email)=LOWER($1) AND is_active LIMIT 1";
        match self {
            Self::Sqlite(pool) => sqlx::query_as(QUERY).bind(email).fetch_optional(pool).await,
            Self::Postgres(pool) => sqlx::query_as(QUERY).bind(email).fetch_optional(pool).await,
        }
    }

    pub(crate) async fn personal_token_team(
        &self,
        email: &str,
    ) -> Result<Option<String>, sqlx::Error> {
        const QUERY:&str="SELECT t.id FROM email_teams t JOIN email_team_members m ON m.team_id=t.id
            WHERE m.user_email=$1 AND m.is_active AND t.is_active AND t.is_personal ORDER BY t.id LIMIT 1";
        match self {
            Self::Sqlite(pool) => {
                sqlx::query_scalar(QUERY)
                    .bind(email)
                    .fetch_optional(pool)
                    .await
            }
            Self::Postgres(pool) => {
                sqlx::query_scalar(QUERY)
                    .bind(email)
                    .fetch_optional(pool)
                    .await
            }
        }
    }
}

