pub(crate) fn hash_api_token(token: &str) -> String {
    use std::fmt::Write as _;
    let mut encoded = String::with_capacity(64);
    for byte in Sha256::digest(token.as_bytes()) {
        write!(encoded, "{byte:02x}").expect("writing to a string is infallible");
    }
    encoded
}

macro_rules! usage_table {
    ($id:literal) => {
        concat!(
            "CREATE TABLE IF NOT EXISTS token_usage_logs (
                id ",
            $id,
            ",
                token_jti VARCHAR(36) NOT NULL,
                user_email VARCHAR(255) NOT NULL,
                timestamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                endpoint VARCHAR(255),
                method VARCHAR(10),
                ip_address VARCHAR(45),
                user_agent TEXT,
                status_code INTEGER,
                response_time_ms INTEGER,
                blocked BOOLEAN NOT NULL DEFAULT FALSE,
                block_reason VARCHAR(255)
            );
            CREATE INDEX IF NOT EXISTS idx_token_usage_logs_token_jti_timestamp
                ON token_usage_logs (token_jti,timestamp);
            CREATE INDEX IF NOT EXISTS idx_token_usage_logs_user_email_timestamp
                ON token_usage_logs (user_email,timestamp);
            CREATE TABLE IF NOT EXISTS cf_token_quota_events (
                id ",
            $id,
            ",
                token_jti VARCHAR(36) NOT NULL,
                timestamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS cf_token_quota_events_token_time
                ON cf_token_quota_events (token_jti,timestamp);"
        )
    };
}

pub(crate) const SQLITE_USAGE_MIGRATION: &str = usage_table!("INTEGER PRIMARY KEY");
pub(crate) const POSTGRES_USAGE_MIGRATION: &str =
    usage_table!("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");

#[derive(Clone, Default, Serialize, sqlx::FromRow)]
pub(crate) struct ApiTokenRecord {
    pub(crate) id: String,
    pub(crate) name: String,
    pub(crate) description: Option<String>,
    pub(crate) user_email: String,
    pub(crate) team_id: Option<String>,
    pub(crate) server_id: Option<String>,
    #[serde(skip)]
    pub(crate) jti: String,
    #[serde(skip)]
    pub(crate) token_hash: String,
    #[serde(skip)]
    pub(crate) resource_scopes: Option<String>,
    #[serde(skip)]
    pub(crate) ip_restrictions: Option<String>,
    #[serde(skip)]
    pub(crate) time_restrictions: Option<String>,
    #[serde(skip)]
    pub(crate) usage_limits: Option<String>,
    #[serde(skip)]
    pub(crate) tags: Option<String>,
    pub(crate) created_at: String,
    pub(crate) expires_at: Option<String>,
    pub(crate) last_used: Option<String>,
    pub(crate) is_active: bool,
    pub(crate) is_revoked: bool,
    pub(crate) revoked_at: Option<String>,
    pub(crate) revoked_by: Option<String>,
    pub(crate) revocation_reason: Option<String>,
}

macro_rules! token_select {
    () => {
        "SELECT t.id,t.name,t.description,t.user_email,t.team_id,t.server_id,t.jti,t.token_hash,
             CAST(t.resource_scopes AS TEXT) AS resource_scopes,CAST(t.ip_restrictions AS TEXT) AS ip_restrictions,
             CAST(t.time_restrictions AS TEXT) AS time_restrictions,CAST(t.usage_limits AS TEXT) AS usage_limits,
             CAST(t.tags AS TEXT) AS tags,CAST(t.created_at AS TEXT) AS created_at,CAST(t.expires_at AS TEXT) AS expires_at,
             CAST(t.last_used AS TEXT) AS last_used,t.is_active,(r.jti IS NOT NULL) AS is_revoked,
             CAST(r.revoked_at AS TEXT) AS revoked_at,r.revoked_by,r.reason AS revocation_reason
          FROM email_api_tokens t LEFT JOIN token_revocations r ON r.jti=t.jti"
    };
}

const TOKEN_BY_ID: &str = concat!(token_select!(), " WHERE t.id=$1");
const TOKEN_BY_JTI: &str = concat!(token_select!(), " WHERE t.jti=$1");

pub(crate) struct TokenList<'a> {
    pub(crate) owner: Option<&'a str>,
    pub(crate) team: Option<&'a str>,
    pub(crate) owner_teams: &'a [String],
    pub(crate) include_inactive: bool,
    pub(crate) limit: i64,
    pub(crate) offset: i64,
}

macro_rules! token_filter {
    ($visible_teams:literal) => {
        concat!(
            " WHERE ($1 OR t.is_active)
                AND (CAST($2 AS TEXT) IS NULL OR t.team_id=$2)
                AND (CAST($3 AS TEXT) IS NULL OR t.user_email=$3 OR t.team_id IN (",
            $visible_teams,
            "))"
        )
    };
}

impl Database {
    pub(crate) async fn managed_token(
        &self,
        id: &str,
    ) -> Result<Option<ApiTokenRecord>, sqlx::Error> {
        match self {
            Self::Sqlite(pool) => {
                sqlx::query_as(TOKEN_BY_ID)
                    .bind(id)
                    .fetch_optional(pool)
                    .await
            }
            Self::Postgres(pool) => {
                sqlx::query_as(TOKEN_BY_ID)
                    .bind(id)
                    .fetch_optional(pool)
                    .await
            }
        }
    }

    pub(crate) async fn token_from_jti(
        &self,
        jti: &str,
    ) -> Result<Option<ApiTokenRecord>, sqlx::Error> {
        match self {
            Self::Sqlite(pool) => {
                sqlx::query_as(TOKEN_BY_JTI)
                    .bind(jti)
                    .fetch_optional(pool)
                    .await
            }
            Self::Postgres(pool) => {
                sqlx::query_as(TOKEN_BY_JTI)
                    .bind(jti)
                    .fetch_optional(pool)
                    .await
            }
        }
    }

    pub(crate) async fn managed_tokens(
        &self,
        filters: TokenList<'_>,
    ) -> Result<(Vec<ApiTokenRecord>, i64), sqlx::Error> {
        let teams = serde_json::to_string(filters.owner_teams)
            .map_err(|error| sqlx::Error::Encode(Box::new(error)))?;
        macro_rules! list {
            ($pool:ident, $teams:literal) => {{
                let rows = sqlx::query_as(concat!(
                    token_select!(),
                    token_filter!($teams),
                    " ORDER BY t.created_at DESC,t.id DESC LIMIT $5 OFFSET $6"
                ))
                .bind(filters.include_inactive)
                .bind(filters.team)
                .bind(filters.owner)
                .bind(&teams)
                .bind(filters.limit)
                .bind(filters.offset)
                .fetch_all($pool);
                let total = sqlx::query_scalar(concat!(
                    "SELECT COUNT(*) FROM email_api_tokens t",
                    token_filter!($teams)
                ))
                .bind(filters.include_inactive)
                .bind(filters.team)
                .bind(filters.owner)
                .bind(&teams)
                .fetch_one($pool);
                tokio::try_join!(rows, total)
            }};
        }
        match self {
            Self::Sqlite(pool) => list!(pool, "SELECT value FROM json_each($4)"),
            Self::Postgres(pool) => {
                list!(pool, "SELECT json_array_elements_text(CAST($4 AS JSON))")
            }
        }
    }
}

